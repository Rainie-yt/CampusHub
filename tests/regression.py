def run(p,lines):
    r=subprocess.run([str(EXE)],cwd=p,input='\n'.join(lines)+'\n',capture_output=True,encoding='utf-8',errors='replace',timeout=5)
    (p/'console.txt').write_text(r.stdout+r.stderr,encoding='utf-8')
    assert r.returncode==0,(p,r.stderr)
    return r.stdout
RESULTS=[]
def check(name,value):
    if not value:
        print(globals().get("o",""))
    assert value,name
    RESULTS.append(name)
    print('PASS',name,flush=True)
def text(p,name):return (p/'data'/name).read_text(encoding='utf-8')
def locked(p,name,lines):
    f=p/'data'/name
    f.chmod(stat.S_IREAD)
    try:return run(p,lines)
    finally:f.chmod(stat.S_IREAD|stat.S_IWRITE)
def files(p):return {x.name:x.read_bytes() for x in (p/'data').iterdir() if x.is_file()}

